const LENGTHS = QUARTER.map(([x, y]) => Math.sqrt(x * x + y * y));
export const PROJECTILE_MAX_DIRECTION_LENGTH = Math.max(...LENGTHS) / SCALE;
export const PROJECTILE_MIN_DIRECTION_LENGTH = Math.min(...LENGTHS) / SCALE;
export const PROJECTILE_HEADING_COUNT = 1024;
export function projectileDir(angle) {
  const index = ((Math.round(angle * 32) % 1024) + 1024) % 1024;
  const [x, y] = QUARTER[index % 256];
  switch (Math.floor(index / 256)) {
    case 0:
      return [x / SCALE, y / SCALE];
    case 1:
      return [-y / SCALE, x / SCALE];
    case 2:
      return [-x / SCALE, -y / SCALE];
    default:
      return [y / SCALE, -x / SCALE];
  }
}
export function projectileDirection(x, y) {
  if (!x && !y) return 0;
  const ax = Math.abs(x),
    ay = Math.abs(y);
  let low = 0,
    high = 256;
  while (high - low > 1) {
    const middle = Math.floor((low + high) / 2),
      [dx, dy] = QUARTER[middle];
    if (dx * ay - dy * ax > 0) low = middle;
    else high = middle;
  }
  const score = (i) => (ax * QUARTER[i][0] + ay * QUARTER[i][1]) / LENGTHS[i];
  const quarter = score(high) > score(low) ? high : low;
  const index =
    x >= 0 ? (y >= 0 ? quarter : 1024 - quarter) : y >= 0 ? 512 - quarter : 512 + quarter;
  return (index % 1024) / 32;
}
export function usesProjectileHeading(object) {
  const shapes =
    object.geometries || (Array.isArray(object.geometry) ? object.geometry : [object.geometry]);
  return (
    ['linear', 'bounce', 'return_to_owner'].includes(object.motion?.kind) &&
    !object.solid &&
    (!object.actor || object.actor.kind === 'none') &&
    (!object.ray || object.ray.kind === 'none') &&
    !shapes.some((shape) => shape?.kind === 'segment')
  );
}
